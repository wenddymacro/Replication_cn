library(haven)
library(data.table)
library(fixest)
setFixest_nthreads(4)
controls <- c("size","age","lev","invt","roa","fixed","cash","RD","big4","HHI","gdp","pop","ind","gdp2","pop2","ind2")
models <- function(file, columns, outcomes, rhs, fe, families) {
  d <- as.data.table(read_dta(file, col_select = tidyselect::all_of(columns)))
  cat(file, nrow(d), "rows\n")
  rbindlist(lapply(seq_along(outcomes), function(i) {
    f <- as.formula(paste(outcomes[i], "~", rhs[i], "|", fe[i]))
    fit <- if (families[i] == "ppml") fepois(f, d, vcov = ~city_year) else feols(f, d, vcov = ~city_year)
    ct <- coeftable(fit)
    data.table(column=i, outcome=outcomes[i], coef=ct["protect",1], se=ct["protect",2], n=nobs(fit))
  }))
}
